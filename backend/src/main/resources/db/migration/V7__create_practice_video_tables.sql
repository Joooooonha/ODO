-- 연습 영상. 08_PracticeVideo_spec.md의 "데이터".
-- 시청 기록, 스레드, 코멘트는 V8(PR B)에서 만든다.

-- 상태: UPLOADING(업로드 시작, 완료 확인 전), READY(완료), DELETING(삭제했고 R2 객체를 지우기 전).
-- 곡이 삭제 표시되어도 영상은 남고 곡 이름을 읽는다. 공연이 지워지면(1차 이후) 영상도 함께 지워진다.
-- 객체 키(practice-videos/{id}/{UUID})에 ID가 들어가므로, 앱이 시퀀스에서 ID를 먼저 받아 키와 함께 넣는다(BY DEFAULT).
CREATE TABLE practice_video (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    performance_id      BIGINT       NOT NULL REFERENCES performance (id) ON DELETE CASCADE,
    song_id             BIGINT       NOT NULL REFERENCES song (id),
    uploader_account_id BIGINT       NOT NULL REFERENCES account (id),
    title               VARCHAR(100) NOT NULL,
    description         VARCHAR(100),
    status              VARCHAR(10)  NOT NULL,
    object_key          VARCHAR(200) NOT NULL,
    content_type        VARCHAR(30)  NOT NULL,
    file_size           BIGINT       NOT NULL,
    play_count          BIGINT       NOT NULL DEFAULT 0,
    upload_deadline     TIMESTAMPTZ  NOT NULL,
    created_at          TIMESTAMPTZ  NOT NULL,
    ready_at            TIMESTAMPTZ,
    updated_at          TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_practice_video_status CHECK (status IN ('UPLOADING', 'READY', 'DELETING')),
    CONSTRAINT ck_practice_video_content_type CHECK (content_type IN ('video/mp4', 'video/quicktime')),
    CONSTRAINT ck_practice_video_file_size CHECK (file_size BETWEEN 1 AND 1073741824),
    CONSTRAINT ck_practice_video_play_count CHECK (play_count >= 0),
    CONSTRAINT uk_practice_video_object_key UNIQUE (object_key)
);

-- 목록(업로드 시각 최신순, 같으면 ID 큰 순). 삭제 중인 영상은 담지 않는다.
CREATE INDEX idx_practice_video_list ON practice_video (performance_id, created_at DESC, id DESC)
    WHERE status IN ('UPLOADING', 'READY');

-- 청소 작업의 대상. 대상 행만 담아 작다.
CREATE INDEX idx_practice_video_upload_deadline ON practice_video (upload_deadline) WHERE status = 'UPLOADING';
CREATE INDEX idx_practice_video_deleting ON practice_video (id) WHERE status = 'DELETING';
