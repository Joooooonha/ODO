-- 팀 멤버십 — 사용자 1명이 여러 팀에 속하고, 여러 팀의 팀장일 수 있게 한다.
--
-- 지금까지는 users.team_id(사용자 1명 = 팀 1개)와 team.leader_id(UNIQUE, 한 사람은
-- 한 팀만 이끈다)로 소속을 표현했다. 이제 소속은 team_member 행 하나하나가 갖는다.
--
-- ⚠️ 이 파일은 **추가만** 한다. 기존 컬럼(users.team_id, team.leader_id)과
-- assignment 테이블은 그대로 둔다. 배포 후 앱이 뜨지 않으면 CI가 직전 jar로
-- 롤백하는데, 그 jar의 엔티티는 옛 컬럼을 기대한다(ddl-auto=validate).
-- 옛 컬럼 제거는 다음 릴리스에서 한다.
--
-- ⚠️ 트랜잭션 안에서 되돌릴 수 있는 문장만 쓴다(CREATE INDEX CONCURRENTLY 금지).
-- Flyway는 PostgreSQL에서 이 파일 전체를 한 트랜잭션으로 실행하므로, 어느 문장에서
-- 실패하든 DB는 V1 상태로 남고 롤백된 직전 jar가 그대로 뜬다.

-- 1) team: 참여 코드, 생성·수정 시각.
--    기존 팀이 언제 만들어졌는지는 기록이 없으므로 created_at은 NULL로 둔다.
ALTER TABLE team ADD COLUMN join_code   character varying(8);
ALTER TABLE team ADD COLUMN created_at  timestamp(6) without time zone;
ALTER TABLE team ADD COLUMN modified_at timestamp(6) without time zone;

-- 2) 기존 팀에 참여 코드 발급.
--    문자 집합은 앱(JoinCodeGenerator)과 같다 — 헷갈리는 0 O 1 I L을 뺀 31자.
--    난수는 gen_random_uuid()(PostgreSQL 13+ 내장, 암호학적 난수)의 바이트를 쓴다.
--    UUID v4는 6·8번 바이트에 버전·변형 비트가 고정돼 있어 그 둘은 건너뛴다.
--
--    서브쿼리 안의 `t.team_id IS NOT NULL`은 일부러 넣은 것이다. 바깥 행을
--    참조하지 않으면 PostgreSQL이 서브쿼리를 한 번만 계산해 **모든 팀이 같은 코드**를
--    받는다. 참조가 있어야 행마다 새로 계산된다.
--    만에 하나 코드가 겹치면 아래 UNIQUE 추가에서 실패하고 V2 전체가 되돌려진다.
UPDATE team t
SET join_code = (
    SELECT string_agg(
               substr('ABCDEFGHJKMNPQRSTUVWXYZ23456789', get_byte(r.b, p.i) % 31 + 1, 1),
               '' ORDER BY p.ord)
    FROM (SELECT decode(replace(gen_random_uuid()::text, '-', ''), 'hex') AS b
          WHERE t.team_id IS NOT NULL) r
    CROSS JOIN unnest(ARRAY[0, 1, 2, 3, 4, 5, 10, 11]) WITH ORDINALITY AS p(i, ord)
);

ALTER TABLE team ALTER COLUMN join_code SET NOT NULL;
ALTER TABLE ONLY team
    ADD CONSTRAINT uk_team_join_code UNIQUE (join_code);

-- 3) 한 사람이 여러 팀의 팀장이 될 수 있게 한다.
--    제약을 푸는 쪽이라 직전 jar에는 영향이 없다.
ALTER TABLE team DROP CONSTRAINT uk55eo7kil7rg126ddxxkrjsf0h;

-- 4) 팀 멤버
CREATE TABLE team_member (
    team_member_id bigint NOT NULL,
    created_at timestamp(6) without time zone,
    modified_at timestamp(6) without time zone,
    team_id bigint NOT NULL,
    user_id bigint NOT NULL,
    role character varying(20) NOT NULL,
    status character varying(20) NOT NULL,
    joined_at timestamp(6) without time zone NOT NULL,
    left_at timestamp(6) without time zone,
    CONSTRAINT team_member_role_check CHECK (((role)::text = ANY ((ARRAY['LEADER'::character varying, 'MEMBER'::character varying])::text[]))),
    CONSTRAINT team_member_status_check CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'LEFT'::character varying, 'KICKED'::character varying])::text[])))
);

ALTER TABLE team_member ALTER COLUMN team_member_id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME team_member_team_member_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY team_member
    ADD CONSTRAINT team_member_pkey PRIMARY KEY (team_member_id);

-- 한 사람-한 팀에 기록은 하나. 재참여는 이 기록을 다시 활성화하고,
-- 같은 참여 요청이 동시에 와도 기록이 하나만 생기게 한다.
-- (엔티티 TeamMember에도 같은 이름으로 선언되어 있다)
ALTER TABLE ONLY team_member
    ADD CONSTRAINT uk_team_member_team_user UNIQUE (team_id, user_id);

ALTER TABLE ONLY team_member
    ADD CONSTRAINT fk_team_member_team FOREIGN KEY (team_id) REFERENCES team(team_id);

ALTER TABLE ONLY team_member
    ADD CONSTRAINT fk_team_member_user FOREIGN KEY (user_id) REFERENCES users(user_id);

-- 내 팀 목록 (user_id로 찾고 ACTIVE만 거른다)
CREATE INDEX idx_team_member_user_status ON team_member USING btree (user_id, status);

-- 팀장은 팀에 정확히 1명. JPA로는 부분 인덱스를 선언할 수 없어 테스트(H2)에는 없다.
CREATE UNIQUE INDEX uk_team_member_one_leader ON team_member USING btree (team_id)
    WHERE ((role)::text = 'LEADER'::text);

-- 5) 기존 데이터 옮겨 담기 (backfill).
--    원래 가입 시각은 어디에도 기록돼 있지 않아 joined_at은 지금 시각으로 둔다.
--    팀장을 먼저 넣고, 그다음 users.team_id 멤버를 넣는다. 팀장이 자기 팀의
--    team_id도 갖고 있으면 이미 LEADER로 들어가 있으므로 건너뛴다.
--    팀장의 team_id가 다른 팀을 가리키면 두 행이 생긴다(A팀 LEADER, B팀 MEMBER).
INSERT INTO team_member (team_id, user_id, role, status, joined_at, created_at, modified_at)
SELECT t.team_id, t.leader_id, 'LEADER', 'ACTIVE', now(), now(), now()
FROM team t
WHERE t.leader_id IS NOT NULL;

INSERT INTO team_member (team_id, user_id, role, status, joined_at, created_at, modified_at)
SELECT u.team_id, u.user_id, 'MEMBER', 'ACTIVE', now(), now(), now()
FROM users u
WHERE u.team_id IS NOT NULL
ON CONFLICT (team_id, user_id) DO NOTHING;

-- 6) 어긋나는 데이터 개수를 배포 로그에 남긴다.
DO $$
DECLARE
    teams_total int;
    no_leader int;
    mismatch int;
    members_total int;
BEGIN
    SELECT count(*) INTO teams_total FROM team;
    SELECT count(*) INTO no_leader FROM team WHERE leader_id IS NULL;
    SELECT count(*) INTO mismatch
    FROM team t JOIN users u ON u.user_id = t.leader_id
    WHERE u.team_id IS DISTINCT FROM t.team_id;
    SELECT count(*) INTO members_total FROM team_member;
    RAISE NOTICE 'V2 backfill: teams=%, team_members=%, teams_without_leader=%, leader_team_mismatch=%',
        teams_total, members_total, no_leader, mismatch;
END $$;
