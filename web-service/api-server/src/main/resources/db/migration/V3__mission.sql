-- Mission — 팀장이 팀원에게 내는 과제, 대상자, 제출, 제출물 코멘트.
--
-- ⚠️ 이 파일은 **추가만** 한다. 기존 테이블·컬럼은 지우거나 바꾸지 않는다.
-- 배포 후 앱이 뜨지 않으면 CI가 직전 jar로 롤백하는데, 그 jar의 엔티티가 기대하는
-- 스키마가 그대로 있어야 ddl-auto=validate를 통과한다.
--
-- ⚠️ 트랜잭션 안에서 되돌릴 수 있는 문장만 쓴다(CREATE INDEX CONCURRENTLY 금지).
-- Flyway는 PostgreSQL에서 이 파일 전체를 한 트랜잭션으로 실행하므로, 어느 문장에서
-- 실패하든 DB는 V2 상태로 남고 롤백된 직전 jar가 그대로 뜬다.

-- 1) 영상 용도. Mission 영상(MISSION)은 분석하지 않고 연습 기록도 만들지 않는다.
--    **DEFAULT가 반드시 있어야 한다.** 기존 행이 GENERAL이 되고, 롤백된 직전 jar가
--    이 컬럼을 모른 채 INSERT해도 성공한다. type과 video_type_check는 건드리지 않는다.
--    PostgreSQL 11+에서 상수 DEFAULT를 단 ADD COLUMN은 테이블을 다시 쓰지 않는다.
ALTER TABLE video ADD COLUMN purpose character varying(20) DEFAULT 'GENERAL' NOT NULL;
ALTER TABLE video ADD CONSTRAINT video_purpose_check
    CHECK (((purpose)::text = ANY ((ARRAY['GENERAL'::character varying, 'MISSION'::character varying])::text[])));

-- 2) mission. 삭제는 soft delete(deleted_at).
CREATE TABLE mission (
    mission_id bigint NOT NULL,
    created_at timestamp(6) without time zone,
    modified_at timestamp(6) without time zone,
    team_id bigint NOT NULL,
    writer_id bigint NOT NULL,
    title character varying(50) NOT NULL,
    description text,
    reference_video_id bigint NOT NULL,
    deleted_at timestamp(6) without time zone
);

ALTER TABLE mission ALTER COLUMN mission_id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME mission_mission_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY mission
    ADD CONSTRAINT mission_pkey PRIMARY KEY (mission_id);
ALTER TABLE ONLY mission
    ADD CONSTRAINT fk_mission_team FOREIGN KEY (team_id) REFERENCES team(team_id);
ALTER TABLE ONLY mission
    ADD CONSTRAINT fk_mission_writer FOREIGN KEY (writer_id) REFERENCES users(user_id);
ALTER TABLE ONLY mission
    ADD CONSTRAINT fk_mission_reference_video FOREIGN KEY (reference_video_id) REFERENCES video(video_id);

-- 팀의 미션 목록(최근 생성순)
CREATE INDEX idx_mission_team_created ON mission USING btree (team_id, created_at);

-- 3) mission_target. 미션을 만들 때 대상자 수만큼 만들고 바꾸지 않는다.
CREATE TABLE mission_target (
    target_id bigint NOT NULL,
    created_at timestamp(6) without time zone,
    modified_at timestamp(6) without time zone,
    mission_id bigint NOT NULL,
    user_id bigint NOT NULL
);

ALTER TABLE mission_target ALTER COLUMN target_id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME mission_target_target_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY mission_target
    ADD CONSTRAINT mission_target_pkey PRIMARY KEY (target_id);
-- 한 미션에 같은 사람은 한 번만 대상자다 (엔티티 MissionTarget에도 같은 이름으로 선언)
ALTER TABLE ONLY mission_target
    ADD CONSTRAINT uk_mission_target_mission_user UNIQUE (mission_id, user_id);
ALTER TABLE ONLY mission_target
    ADD CONSTRAINT fk_mission_target_mission FOREIGN KEY (mission_id) REFERENCES mission(mission_id);
ALTER TABLE ONLY mission_target
    ADD CONSTRAINT fk_mission_target_user FOREIGN KEY (user_id) REFERENCES users(user_id);

-- 4) mission_submission. 제출 시각은 created_at이다.
CREATE TABLE mission_submission (
    submission_id bigint NOT NULL,
    created_at timestamp(6) without time zone,
    modified_at timestamp(6) without time zone,
    target_id bigint NOT NULL,
    video_id bigint NOT NULL,
    content text
);

ALTER TABLE mission_submission ALTER COLUMN submission_id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME mission_submission_submission_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY mission_submission
    ADD CONSTRAINT mission_submission_pkey PRIMARY KEY (submission_id);
-- 대상자 1인당 제출 1건. 같은 제출이 동시에 와도 한 건만 들어간다.
-- 대상자가 아닌 사람은 target_id가 없으므로 제출 행을 만들 수 없다.
-- (엔티티 MissionSubmission에도 같은 이름으로 선언)
ALTER TABLE ONLY mission_submission
    ADD CONSTRAINT uk_mission_submission_target UNIQUE (target_id);
ALTER TABLE ONLY mission_submission
    ADD CONSTRAINT fk_mission_submission_target FOREIGN KEY (target_id) REFERENCES mission_target(target_id);
ALTER TABLE ONLY mission_submission
    ADD CONSTRAINT fk_mission_submission_video FOREIGN KEY (video_id) REFERENCES video(video_id);

-- 5) submission_comment. 수정·삭제 없음.
CREATE TABLE submission_comment (
    comment_id bigint NOT NULL,
    created_at timestamp(6) without time zone,
    modified_at timestamp(6) without time zone,
    submission_id bigint NOT NULL,
    writer_id bigint NOT NULL,
    content text NOT NULL
);

ALTER TABLE submission_comment ALTER COLUMN comment_id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME submission_comment_comment_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY submission_comment
    ADD CONSTRAINT submission_comment_pkey PRIMARY KEY (comment_id);
ALTER TABLE ONLY submission_comment
    ADD CONSTRAINT fk_submission_comment_submission FOREIGN KEY (submission_id) REFERENCES mission_submission(submission_id);
ALTER TABLE ONLY submission_comment
    ADD CONSTRAINT fk_submission_comment_writer FOREIGN KEY (writer_id) REFERENCES users(user_id);

-- 제출물의 코멘트 목록(작성순)
CREATE INDEX idx_submission_comment_submission_created ON submission_comment USING btree (submission_id, created_at);
