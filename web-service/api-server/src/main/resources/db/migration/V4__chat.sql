-- 채팅 — 팀 채팅방(팀마다 1개)과 DM(두 사람마다 1개), 채팅 멤버, 메시지.
--
-- ⚠️ 이 파일은 **추가만** 한다. 기존 테이블·컬럼은 지우거나 바꾸지 않는다.
-- 배포 후 앱이 뜨지 않으면 CI가 직전 jar로 롤백하는데, 그 jar의 엔티티는 이 테이블을
-- 모른다. Hibernate validate는 모르는 테이블을 무시하므로 그대로 뜬다.
--
-- ⚠️ 트랜잭션 안에서 되돌릴 수 있는 문장만 쓴다(CREATE INDEX CONCURRENTLY 금지).
-- Flyway는 PostgreSQL에서 이 파일 전체를 한 트랜잭션으로 실행하므로, 어느 문장에서
-- 실패하든 DB는 V3 상태로 남고 롤백된 직전 jar가 그대로 뜬다.
--
-- 시각 컬럼은 timestamptz다(기존 테이블의 timestamp without time zone과 다르다).
-- 값은 서버(JVM) 시계가 아니라 DB가 찍는다. 서버가 2대 이상이어도 시계가 하나다.

-- 1) chat_room
--    last_seq는 그 방에 마지막으로 부여한 메시지 번호다. 메시지 저장은 이 행을
--    UPDATE로 잠그고 번호를 하나 올린다 — 같은 방의 저장이 이 행에서 한 줄로 선다.
--    마지막 메시지 미리보기 칸은 두지 않는다. message(room_id, last_seq)로 찾는다.
CREATE TABLE chat_room (
    room_id bigint NOT NULL,
    type character varying(10) NOT NULL,
    team_id bigint,
    dm_user_low bigint,
    dm_user_high bigint,
    last_seq bigint DEFAULT 0 NOT NULL,
    created_at timestamp(6) with time zone DEFAULT now() NOT NULL,
    modified_at timestamp(6) with time zone DEFAULT now() NOT NULL,
    CONSTRAINT chat_room_type_check CHECK (((type)::text = ANY ((ARRAY['TEAM'::character varying, 'DM'::character varying])::text[]))),
    -- 팀 방은 팀만, DM은 두 사람만 가진다. DM의 두 사람은 작은 id가 low다.
    CONSTRAINT chat_room_shape_check CHECK (
        (((type)::text = 'TEAM'::text) AND team_id IS NOT NULL AND dm_user_low IS NULL AND dm_user_high IS NULL)
        OR (((type)::text = 'DM'::text) AND team_id IS NULL AND dm_user_low IS NOT NULL AND dm_user_high IS NOT NULL
            AND dm_user_low < dm_user_high)),
    CONSTRAINT chat_room_last_seq_check CHECK (last_seq >= 0)
);

ALTER TABLE chat_room ALTER COLUMN room_id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME chat_room_room_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY chat_room
    ADD CONSTRAINT chat_room_pkey PRIMARY KEY (room_id);

-- 팀마다 팀 채팅방은 정확히 1개. DM은 team_id가 NULL이라 걸리지 않는다.
-- (엔티티 ChatRoom에도 같은 이름으로 선언)
ALTER TABLE ONLY chat_room
    ADD CONSTRAINT uk_chat_room_team UNIQUE (team_id);

-- 두 사람마다 DM은 1개. 부분 인덱스가 아니라 일반 UNIQUE로 충분하다 — 팀 방은
-- 위 CHECK로 두 칸이 항상 NULL이고, PostgreSQL UNIQUE는 NULL끼리 같은 값으로 보지 않는다.
-- 같은 두 사람이 동시에 DM을 열어도 INSERT ... ON CONFLICT로 방 하나만 남는다.
ALTER TABLE ONLY chat_room
    ADD CONSTRAINT uk_chat_room_dm_pair UNIQUE (dm_user_low, dm_user_high);

ALTER TABLE ONLY chat_room
    ADD CONSTRAINT fk_chat_room_team FOREIGN KEY (team_id) REFERENCES team(team_id);
ALTER TABLE ONLY chat_room
    ADD CONSTRAINT fk_chat_room_dm_low FOREIGN KEY (dm_user_low) REFERENCES users(user_id);
ALTER TABLE ONLY chat_room
    ADD CONSTRAINT fk_chat_room_dm_high FOREIGN KEY (dm_user_high) REFERENCES users(user_id);

-- 2) chat_room_member
--    재가입은 새 행이 아니라 기존 행을 다시 ACTIVE로 만든다.
--    last_read_seq는 이번 범위에서는 초기값만 쓴다(가입 시점의 last_seq).
--    modified_at은 상태를 바꾸는 모든 문장이 now()로 직접 갱신한다 — 서버마다 5초마다
--    "최근에 바뀐 멤버"를 이 컬럼으로 찾는다.
CREATE TABLE chat_room_member (
    member_id bigint NOT NULL,
    room_id bigint NOT NULL,
    user_id bigint NOT NULL,
    status character varying(10) NOT NULL,
    last_read_seq bigint NOT NULL,
    created_at timestamp(6) with time zone DEFAULT now() NOT NULL,
    modified_at timestamp(6) with time zone DEFAULT now() NOT NULL,
    CONSTRAINT chat_room_member_status_check CHECK (((status)::text = ANY ((ARRAY['ACTIVE'::character varying, 'LEFT'::character varying, 'KICKED'::character varying])::text[])))
);

ALTER TABLE chat_room_member ALTER COLUMN member_id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME chat_room_member_member_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY chat_room_member
    ADD CONSTRAINT chat_room_member_pkey PRIMARY KEY (member_id);

-- 한 사람-한 방에 행은 하나 (엔티티 ChatRoomMember에도 같은 이름으로 선언)
ALTER TABLE ONLY chat_room_member
    ADD CONSTRAINT uk_chat_room_member_room_user UNIQUE (room_id, user_id);

ALTER TABLE ONLY chat_room_member
    ADD CONSTRAINT fk_chat_room_member_room FOREIGN KEY (room_id) REFERENCES chat_room(room_id);
ALTER TABLE ONLY chat_room_member
    ADD CONSTRAINT fk_chat_room_member_user FOREIGN KEY (user_id) REFERENCES users(user_id);

-- 내 방 목록 (user_id로 찾고 ACTIVE만 거른다)
CREATE INDEX idx_chat_room_member_user_status ON chat_room_member USING btree (user_id, status);
-- 5초 재확인 (최근에 바뀐 멤버)
CREATE INDEX idx_chat_room_member_modified ON chat_room_member USING btree (modified_at);

-- 3) message
--    seq는 방 안의 순서 번호(1부터 빈틈 없이). created_at은 번호를 받는 문장에서
--    함께 받은 시각이라 기본값을 두지 않는다 — 빼먹으면 오류로 드러나야 한다.
--    시스템 메시지(입장·나가기·추방)는 보낸 사람이 없고, client_message_id에
--    사건마다 만든 UUID를 넣는다.
CREATE TABLE message (
    message_id bigint NOT NULL,
    room_id bigint NOT NULL,
    seq bigint NOT NULL,
    sender_id bigint,
    type character varying(10) NOT NULL,
    content text NOT NULL,
    client_message_id uuid NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT message_type_check CHECK (((type)::text = ANY ((ARRAY['TEXT'::character varying, 'SYSTEM'::character varying])::text[]))),
    CONSTRAINT message_sender_check CHECK (
        (((type)::text = 'TEXT'::text) AND sender_id IS NOT NULL)
        OR (((type)::text = 'SYSTEM'::text) AND sender_id IS NULL)),
    -- 길이는 코드 포인트로 센다(char_length). 브라우저·서버도 같은 기준이다.
    CONSTRAINT message_content_check CHECK (content <> ''::text AND (((type)::text <> 'TEXT'::text) OR char_length(content) <= 2000)),
    CONSTRAINT message_seq_check CHECK (seq >= 1)
);

ALTER TABLE message ALTER COLUMN message_id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME message_message_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY message
    ADD CONSTRAINT message_pkey PRIMARY KEY (message_id);

-- 안전망. 정상 경로(방 행 잠금 아래에서 번호 부여)에서는 걸리지 않는다.
-- 걸리면 번호 부여에 버그가 있다는 뜻이므로 조용히 넘기지 않고 오류가 나야 한다.
-- "방 X의 N번 이후/이전" 조회 인덱스를 겸한다. (엔티티 ChatMessage에도 선언)
ALTER TABLE ONLY message
    ADD CONSTRAINT uk_message_room_seq UNIQUE (room_id, seq);

-- 같은 메시지를 두 번 저장하지 않는다(재전송). 보낸 사람을 키에 넣어, 남의 UUID로
-- 남의 번호를 돌려받지 못하게 한다. (엔티티 ChatMessage에도 선언)
ALTER TABLE ONLY message
    ADD CONSTRAINT uk_message_sender_client UNIQUE (sender_id, client_message_id);

-- 시스템 메시지 중복 방지. sender_id가 NULL이라 위 UNIQUE로는 막히지 않는다
-- (NULL끼리는 다른 값). JPA로 선언할 수 없는 부분 인덱스라 엔티티에는 없다.
CREATE UNIQUE INDEX uk_message_system_client ON message USING btree (client_message_id)
    WHERE ((type)::text = 'SYSTEM'::text);

ALTER TABLE ONLY message
    ADD CONSTRAINT fk_message_room FOREIGN KEY (room_id) REFERENCES chat_room(room_id);
ALTER TABLE ONLY message
    ADD CONSTRAINT fk_message_sender FOREIGN KEY (sender_id) REFERENCES users(user_id);

-- 4) 기존 팀 옮겨 담기 (backfill).
--    팀마다 팀 채팅방 1개, 활동 중(ACTIVE) 팀 멤버마다 채팅 멤버 1개.
--    방이 막 생겨 last_seq가 0이므로 last_read_seq도 0이다.
--    나가거나 추방된 팀 멤버는 채팅 멤버를 만들지 않는다 — 재가입하면 그때 생긴다.
INSERT INTO chat_room (type, team_id)
SELECT 'TEAM', t.team_id
FROM team t;

INSERT INTO chat_room_member (room_id, user_id, status, last_read_seq)
SELECT r.room_id, m.user_id, 'ACTIVE', 0
FROM team_member m
JOIN chat_room r ON r.team_id = m.team_id
WHERE m.status = 'ACTIVE';

-- 5) 옮겨 담은 개수를 배포 로그에 남긴다.
DO $$
DECLARE
    teams_total int;
    team_rooms int;
    active_members int;
    chat_members int;
BEGIN
    SELECT count(*) INTO teams_total FROM team;
    SELECT count(*) INTO team_rooms FROM chat_room WHERE type = 'TEAM';
    SELECT count(*) INTO active_members FROM team_member WHERE status = 'ACTIVE';
    SELECT count(*) INTO chat_members FROM chat_room_member;
    RAISE NOTICE 'V4 backfill: teams=%, team_rooms=%, active_team_members=%, chat_members=%',
        teams_total, team_rooms, active_members, chat_members;
END $$;
